#![cfg(any(feature = "test_utils", test))]

use std::sync::Arc;

use crate::{MockPal, PlatformAbstractionLayer};

/// Creates a `PlatformAbstractionLayer` instance that is pre-configured to return default / stub
/// values from all of its methods. Under the hood it uses `crate::MockPal`, which is generated by
/// `mockall`. If you need more intricate behavior or assertions, use `crate::MockPal` directly.
pub fn new_stub_pal() -> Arc<dyn PlatformAbstractionLayer> {
    let mut mock = MockPal::new();
    mock.expect_get_resumed_at().return_const(None);
    Arc::new(mock)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn new_stub_pal_returns_stub() {
        let pal = new_stub_pal();

        // Ensure `get_resumed_at` can be called multiple times and not just once.
        assert_eq!(pal.get_resumed_at(), None);
        assert_eq!(pal.get_resumed_at(), None);
    }
}
