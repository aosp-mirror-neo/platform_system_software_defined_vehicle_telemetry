//! Utility functions for unit tests.

use log::trace;
use rand::{distributions::Alphanumeric, thread_rng, Rng};

/// Generate a unique Data Tunnel topic name for testing.
///
/// TODO(b/343140446): We should clean up data tunnel topics.
pub fn unique_dt_topic_name() -> String {
    const PREFIX: &str = "TelemetryTest";
    const SUFFIX_LEN: usize = 30;
    const _: () = assert!(PREFIX.len() + SUFFIX_LEN <= 48, "Generated data tunnel topic name must be less than or equal to Data Tunnel's maximum topic name length.");

    let suffix = thread_rng()
        .sample_iter(&Alphanumeric)
        .take(SUFFIX_LEN)
        .map(char::from)
        .collect::<String>();
    let name = format!("{PREFIX}{suffix}");

    // Print the generated topic name for easier debugging - we print it to both logs and stderr, so
    // it shows up in atest output as well.
    let msg = format!("Generated data tunnel topic name: {name}");
    trace!("{msg}");
    eprintln!("{msg}");

    name
}

/// Macro for generating parameterized tests. The first argument is a common test name prefix for
/// all generated tests. The second argument is a lambda that takes a number of arguments, and
/// includes the actual test body. Then follow multiple lines of `test_name_suffix: (arg1, arg2,
/// ..., argN,),`, one per test case.
///
/// NOTE: You need to ensure that your `rust_test` build target lists `libpaste` in `proc_macros`
///       dependency, because that macro is used by the code generated by `parameterized_test`.
/// NOTE: Async tests are not currently supported.
///
/// Example:
///
/// ```
/// parameterized_test!(
///     is_equal,
///
///     |expected, a, b| {
///         assert!((a == b) == expected);
///     },
///
///     two_and_four: (false, 2, 4,),
///     two_and_two: (true, 2, 2,),
/// )
/// ```
///
/// This will generate the following code for you:
///
/// ```no_run
/// paste::paste! {
///     #[test]
///     fn [<is_equal _ two_and_four>]() {
///         (|expected, a, b| {
///             assert!((a == b) == expected);
///         })(
///             false,
///             2,
///             4,
///         )
///     }
///
///     #[test]
///     fn [<is_equal _ two_and_two>]() {
///         (|expected, a, b| {
///             assert!((a == b) == expected);
///         })(
///             true,
///             2,
///             2,
///         )
///     }
/// }
/// ```
#[macro_export]
macro_rules! parameterized_test {
    ($name_prefix:ident, $test_fn:expr, $($case_name:ident: ($($arg:expr,)+),)*) => {
        paste::paste! {
            $(
                #[test]
                fn [<$name_prefix _ $case_name>]() {
                    ($test_fn)(
                        $($arg,)+
                    )
                }
            )*
        }
    }
}

#[cfg(test)]
mod tests {
    use std::thread;
    use tokio::time::{sleep, Duration};

    // These tests cannot be inside of the `sdv_telemetry_test_utils_macros`, because that crate is
    // a proc macro crate.

    #[tokio::test]
    #[sdv_telemetry_test_utils_macros::timeout]
    async fn timeout_does_not_trigger() {
        sleep(Duration::from_millis(100)).await;
    }

    #[tokio::test]
    #[sdv_telemetry_test_utils_macros::timeout]
    #[should_panic(expected = "Test timeout of 1000ms reached (call stalled for ")]
    async fn timeout_triggers() {
        sleep(Duration::from_millis(1100)).await;
    }

    #[tokio::test]
    #[sdv_telemetry_test_utils_macros::timeout(100)]
    #[should_panic(expected = "Test timeout of 100ms reached (call stalled for ")]
    async fn timeout_triggers_with_explicit_duration() {
        sleep(Duration::from_millis(200)).await;
    }

    #[tokio::test]
    #[sdv_telemetry_test_utils_macros::timeout(100)]
    #[should_panic(expected = "Test timeout of 100ms reached!")]
    async fn timeout_triggers_after_sync_sleep() {
        thread::sleep(Duration::from_millis(200));
        sleep(Duration::MAX).await;
    }
}
